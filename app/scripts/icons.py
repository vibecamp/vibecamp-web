import io
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

NAMES = [
    'add', 'add_shopping_cart', 'arrow_back', 'bookmark', 'calendar_add_on', 'calendar_today',
    'chevron_right', 'close', 'confirmation_number', 'edit_calendar', 'error', 'filter_list', 'gavel',
    'hourglass_top', 'info', 'location_on', 'logout', 'mail', 'map', 'menu', 'open_in_new',
    'person', 'remove', 'schedule', 'search', 'share', 'shopping_bag',
]
APP = Path(__file__).resolve().parent.parent
if len(sys.argv) != 2:
    sys.exit('usage: uv run scripts/icons.py <Material Symbols Outlined .woff2>')
FONT = Path(sys.argv[1])
OUT = APP / 'src/components/core/icon-paths.ts'

ttf = TTFont(FONT)
upm = ttf['head'].unitsPerEm
ttf.flavor = None
raw = io.BytesIO()
ttf.save(raw)
font = hb.Font(hb.Face(hb.Blob(raw.getvalue())))


def path(name: str, fill: int) -> str:
    font.set_variations({'FILL': fill, 'wght': 400, 'GRAD': 0, 'opsz': 24})
    buf = hb.Buffer()
    buf.add_str(name)
    buf.guess_segment_properties()
    hb.shape(font, buf, {'liga': True})
    if len(buf.glyph_infos) != 1:
        sys.exit(f'No single glyph for {name!r}')
    pen = SVGPathPen(None, ntos=lambda v: f'{round(v, 1):g}')
    font.draw_glyph_with_pen(buf.glyph_infos[0].codepoint, TransformPen(pen, (1, 0, 0, -1, 0, upm)))
    return pen.getCommands()


lines = ['// Generated by scripts/icons.py from Material Symbols Outlined (wght 400, GRAD 0, opsz 24).',
         f'export const ICON_VIEWBOX = \'0 0 {upm} {upm}\'', '', 'export const ICON_PATHS = {']
for name in sorted(NAMES):
    outline, filled = path(name, 0), path(name, 1)
    value = f"'{outline}'" if outline == filled else f"['{outline}', '{filled}']"
    lines.append(f'    {name}: {value},')
lines += ['} as const satisfies Record<string, string | readonly [string, string]>', '']
OUT.write_text('\n'.join(lines))
print(f'Wrote {len(NAMES)} icons to {OUT.relative_to(APP)}')
